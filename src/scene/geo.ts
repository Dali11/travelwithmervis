// Real outlines from Natural Earth (public domain), simplified.
// Flat arrays of lon,lat pairs.

export type LonLat = [number, number];

function pairs(a: number[]): LonLat[] {
  const out: LonLat[] = [];
  for (let i = 0; i < a.length; i += 2) out.push([a[i], a[i + 1]]);
  return out;
}

